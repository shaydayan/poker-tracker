// Vite plugin: after a build, writes dist/sw.js, the service worker that keeps the app working offline. It lists every
// built file (so the whole app is cached on first visit) and is named after a hash of their contents, so any new build
// replaces the old cache. Nothing here touches the app's data, which lives in IndexedDB, not in this cache.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const files = (dir) => readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? files(join(dir, f)) : [join(dir, f)]))

const worker = (version, list) => `// Generated by scripts/offline-cache.js at build time. Do not edit.
const CACHE = 'poker-tracker-${version}'
const FILES = ${JSON.stringify(list, null, 2)}

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('poker-tracker-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

// The app from the cache first (it opens with no signal), the network only for anything not cached.
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return
  // ignoreVary: the server marks files Vary: Origin, and the page asks for its scripts with an Origin the cached copies lack.
  const cached = caches.match(req.mode === 'navigate' ? 'index.html' : req, { ignoreVary: true })
  e.respondWith(cached.then((r) => r || fetch(req)))
})
`

export function offlineCache() {
  let outDir
  return {
    name: 'offline-cache',
    apply: 'build',
    configResolved(config) {
      outDir = join(config.root, config.build.outDir)
    },
    closeBundle() {
      const all = files(outDir).filter((f) => !f.endsWith(`${sep}sw.js`)).sort()
      const list = ['./', ...all.map((f) => relative(outDir, f).split(sep).join('/'))]
      const hash = createHash('sha256').update(worker('', list)) // a change to the worker itself also makes a new cache
      for (const f of all) hash.update(relative(outDir, f)).update(readFileSync(f))
      writeFileSync(join(outDir, 'sw.js'), worker(hash.digest('hex').slice(0, 12), list))
    },
  }
}
